import type { ExecutionContext, ScheduledController } from "@cloudflare/workers-types";
import { encryptBackup } from "./backup-crypto";
import { isRecord } from "./records";

export const BACKUP_PREFIX = "d1";
export const BACKUP_MANIFEST_KEY = "d1/manifest.json";
export const BACKUP_KEEP_DAYS = 30;
export const BACKUP_TABLE_QUERY =
  "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' ORDER BY name";

const DAY_MS = 24 * 60 * 60 * 1000;
const ENCODER = new TextEncoder();

type Row = Record<string, unknown>;

/** One table prepared for the SQL dump. */
export type DumpTable = {
  name: string;
  ddl: string;
  columns: string[];
  rows: Row[];
};

/** One archive recorded in the R2 manifest. */
export type BackupManifestEntry = {
  key: string;
  createdAt: string;
  createdAtJst: string;
  keyId: string;
  algorithm: "AES-256-GCM";
  iv: string;
  sha256: string;
  sizeBytes: number;
  encryptedBytes: number;
  tables: { name: string; rows: number }[];
};

export type BackupManifest = {
  version: 1;
  entries: BackupManifestEntry[];
};

/** Minimal D1 surface used to read the dump (D1Database is assignable). */
export type DumpSource = {
  prepare: (query: string) => { all: () => Promise<{ results?: unknown[] }> };
};


/** Minimal R2 surface used by the backup (R2Bucket is assignable). */
export type BackupBucket = {
  put: (key: string, value: Uint8Array, options?: { httpMetadata?: { contentType?: string } }) => Promise<unknown>;
  get: (key: string) => Promise<{ text: () => Promise<string> } | null>;
  list: (options?: { prefix?: string; cursor?: string }) => Promise<{
    objects: { key: string }[];
    truncated: boolean;
    cursor?: string;
  }>;
  delete: (key: string) => Promise<void>;
};

/** Bindings used by the scheduled backup handler. */
export type BackupEnv = {
  DB?: DumpSource;
  BACKUPS?: BackupBucket;
  SESSION_SECRET?: string;
};

export type BackupResult = {
  key: string;
  keyId: string;
  rows: number;
  sizeBytes: number;
  encryptedBytes: number;
  pruned: string[];
};

function quoteIdentifier(name: string): string {
  return `"${name.replaceAll('"', '""')}"`;
}

function quoteValue(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error("numeric value is not finite");
    return String(value);
  }
  if (typeof value === "bigint") return value.toString();
  if (typeof value === "boolean") return value ? "1" : "0";
  if (value instanceof Uint8Array) {
    return `X'${Array.from(value, (byte) => byte.toString(16).padStart(2, "0")).join("")}'`;
  }
  if (typeof value === "string") return `'${value.replaceAll("'", "''")}'`;
  return `'${JSON.stringify(value).replaceAll("'", "''")}'`;
}

/** Renders a self-contained SQL dump that replaces each table on restore. */
export function renderSqlDump(tables: readonly DumpTable[]): string {
  const lines = ["-- SIFTQ D1 backup", "-- generated by the scheduled backup handler", ""];
  for (const table of tables) {
    lines.push(`DROP TABLE IF EXISTS ${quoteIdentifier(table.name)};`);
    lines.push(`${table.ddl.trim().replace(/;?$/, ";")}`);
    lines.push("");
    if (table.rows.length === 0) continue;
    const columns = table.columns.map(quoteIdentifier).join(", ");
    for (const row of table.rows) {
      const values = table.columns.map((column) => quoteValue(row[column])).join(", ");
      lines.push(`INSERT INTO ${quoteIdentifier(table.name)} (${columns}) VALUES (${values});`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

/** Compresses bytes with gzip using the platform CompressionStream. */
export async function gzip(bytes: Uint8Array): Promise<Uint8Array<ArrayBuffer>> {
  const stream = new Blob([new Uint8Array(bytes)]).stream().pipeThrough(new CompressionStream("gzip"));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

/** Decompresses gzip bytes using the platform DecompressionStream. */
export async function gunzip(bytes: Uint8Array): Promise<Uint8Array<ArrayBuffer>> {
  const stream = new Blob([new Uint8Array(bytes)]).stream().pipeThrough(new DecompressionStream("gzip"));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

/** Returns the lowercase hex SHA-256 digest of the given bytes. */
export async function sha256Hex(bytes: Uint8Array): Promise<string> {
  const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", new Uint8Array(bytes)));
  return Array.from(digest, (byte) => byte.toString(16).padStart(2, "0")).join("");
}

/** Reads the DDL and rows of every user table in the database. */
export async function buildDump(db: DumpSource): Promise<DumpTable[]> {
  const tableResult = await db.prepare(BACKUP_TABLE_QUERY).all();
  const tables: DumpTable[] = [];
  for (const raw of tableResult.results ?? []) {
    if (!isRecord(raw)) continue;
    const tableName = raw["name"];
    const ddl = raw["sql"];
    if (typeof tableName !== "string" || typeof ddl !== "string") continue;
    const info = await db.prepare(`PRAGMA table_info(${quoteIdentifier(tableName)})`).all();
    const columns = (info.results ?? []).flatMap((column) =>
      isRecord(column) && typeof column["name"] === "string" ? [column["name"]] : [],
    );
    const data = await db.prepare(`SELECT * FROM ${quoteIdentifier(tableName)}`).all();
    const rows = (data.results ?? []).filter(isRecord);
    tables.push({ name: tableName, ddl, columns, rows });
  }
  return tables;
}

/** R2 key for the archive created at the given instant (UTC date). */
export function backupKey(now: Date): string {
  const date = now.toISOString().slice(0, 10);
  return `${BACKUP_PREFIX}/${date.replaceAll("-", "/")}/siftq.sql.gz.enc`;
}

function dateFromKey(key: string): Date | null {
  const match = /^d1\/(\d{4})\/(\d{2})\/(\d{2})\//.exec(key);
  if (match === null) return null;
  const date = new Date(`${match[1]}-${match[2]}-${match[3]}T00:00:00.000Z`);
  return Number.isNaN(date.getTime()) ? null : date;
}

function jstTimestamp(now: Date): string {
  return new Date(now.getTime() + 9 * 60 * 60 * 1000).toISOString().replace("Z", "+09:00");
}

function isManifestEntry(value: unknown): value is BackupManifestEntry {
  if (typeof value !== "object" || value === null) return false;
  return "key" in value && typeof value.key === "string" && "createdAt" in value && typeof value.createdAt === "string";
}

async function readManifest(bucket: BackupBucket): Promise<BackupManifest> {
  const object = await bucket.get(BACKUP_MANIFEST_KEY);
  if (object === null) return { version: 1, entries: [] };
  try {
    const parsed: unknown = JSON.parse(await object.text());
    if (typeof parsed !== "object" || parsed === null || !("entries" in parsed)) return { version: 1, entries: [] };
    const rawEntries: unknown[] = Array.isArray(parsed.entries) ? parsed.entries : [];
    return { version: 1, entries: rawEntries.filter(isManifestEntry) };
  } catch {
    return { version: 1, entries: [] };
  }
}

/** Deletes archives older than the retention window. */
export async function pruneBackups(bucket: BackupBucket, now: Date, keepDays = BACKUP_KEEP_DAYS): Promise<string[]> {
  const cutoff = new Date(now.getTime() - keepDays * DAY_MS);
  const deleted: string[] = [];
  let cursor: string | undefined;
  do {
    const options: Parameters<BackupBucket["list"]>[0] = { prefix: `${BACKUP_PREFIX}/` };
    if (cursor !== undefined) options.cursor = cursor;
    const page = await bucket.list(options);
    for (const object of page.objects ?? []) {
      const date = dateFromKey(object.key);
      if (date === null || date.getTime() >= cutoff.getTime()) continue;
      await bucket.delete(object.key);
      deleted.push(object.key);
    }
    cursor = page.truncated ? page.cursor : undefined;
  } while (cursor !== undefined);
  return deleted;
}

/** Creates, stores and records one encrypted backup archive. */
export async function runBackup(env: BackupEnv, now: Date = new Date()): Promise<BackupResult> {
  const { DB: db, BACKUPS: bucket, SESSION_SECRET: secret } = env;
  if (db === undefined || bucket === undefined || secret === undefined || secret.length === 0) {
    throw new Error("backup bindings are not configured");
  }
  const tables = await buildDump(db);
  const plaintext = ENCODER.encode(renderSqlDump(tables));
  const compressed = await gzip(plaintext);
  const { payload, keyId, iv } = await encryptBackup(compressed, secret);
  const key = backupKey(now);
  await bucket.put(key, payload, { httpMetadata: { contentType: "application/octet-stream" } });

  const entry: BackupManifestEntry = {
    key,
    createdAt: now.toISOString(),
    createdAtJst: jstTimestamp(now),
    keyId,
    algorithm: "AES-256-GCM",
    iv,
    sha256: await sha256Hex(plaintext),
    sizeBytes: plaintext.length,
    encryptedBytes: payload.length,
    tables: tables.map((table) => ({ name: table.name, rows: table.rows.length })),
  };
  const manifest = await readManifest(bucket);
  const cutoff = now.getTime() - BACKUP_KEEP_DAYS * DAY_MS;
  const entries = [entry, ...manifest.entries.filter((item) => item.key !== key && new Date(item.createdAt).getTime() >= cutoff)];
  await bucket.put(BACKUP_MANIFEST_KEY, ENCODER.encode(JSON.stringify({ version: 1, entries } satisfies BackupManifest, null, 2)), {
    httpMetadata: { contentType: "application/json" },
  });
  const pruned = await pruneBackups(bucket, now);
  return {
    key,
    keyId,
    rows: tables.reduce((total, table) => total + table.rows.length, 0),
    sizeBytes: plaintext.length,
    encryptedBytes: payload.length,
    pruned,
  };
}

/** Cron entry point: creates the daily backup; failures surface in Workers logs. */
export async function scheduled(_controller: ScheduledController, env: BackupEnv, _ctx: ExecutionContext): Promise<void> {
  await runBackup(env);
}

