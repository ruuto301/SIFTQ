/**
 * Description 編集 / プレビュー tabs, shared by the task form and the DS screen.
 * Embedded in `task-form-scripts.ts` and `ds-scripts.ts`; both screens render the
 * same `[data-description-tabs]` markup.
 */
export const DESCRIPTION_TABS_SCRIPT = [
  "function descriptionEditorValue(editor) {",
  '  const images = Array.prototype.slice.call(editor.querySelectorAll("img[data-token]"));',
  "  const replacements = images.map(function (image) {",
  '    const span = document.createElement("span");',
  '    span.textContent = image.getAttribute("data-token") || "";',
  "    image.parentNode.replaceChild(span, image);",
  "    return { image: image, span: span };",
  "  });",
  '  const value = editor.innerText.replace(/\\n$/, "");',
  "  replacements.forEach(function (replacement) {",
  "    if (replacement.span.parentNode) replacement.span.parentNode.replaceChild(replacement.image, replacement.span);",
  "  });",
  "  return value;",
  "}",
  "function descriptionTabButtons(root) {",
  '  return Array.prototype.slice.call(root.querySelectorAll("[data-description-tab]"));',
  "}",
  "function descriptionTabButton(node) {",
  '  return node && node.closest ? node.closest("[data-description-tab]") : null;',
  "}",
  "function descriptionTabRoot(node) {",
  '  return node && node.closest ? node.closest("[data-description-tabs]") : null;',
  "}",
  "function selectDescriptionTab(root, name) {",
  '  const preview = name === "preview";',
  "  // Read the live editor before the edit panel is hidden so an unsynced edit still previews.",
  '  const text = preview ? descriptionPreviewText(root) : "";',
  "  descriptionTabButtons(root).forEach(function (button) {",
  "    const selected = button.getAttribute(\"data-description-tab\") === name;",
  '    button.setAttribute("aria-selected", selected ? "true" : "false");',
  '    button.setAttribute("tabindex", selected ? "0" : "-1");',
  "  });",
  '  Array.prototype.slice.call(root.querySelectorAll("[data-description-panel]")).forEach(function (panel) {',
  '    panel.hidden = panel.getAttribute("data-description-panel") !== name;',
  "  });",
  "  if (preview) refreshDescriptionPreview(root, text);",
  "}",
  "function descriptionPreviewText(root) {",
  "  // The task form edits a contenteditable; the DS screen edits a textarea.",
  '  const editor = root.querySelector("[data-description-editor]");',
  '  if (editor && !editor.closest("[hidden]")) return descriptionEditorValue(editor);',
  '  const textarea = root.querySelector("textarea[data-description-value]");',
  "  if (textarea) return textarea.value;",
  '  return editor ? descriptionEditorValue(editor) : "";',
  "}",
  "function refreshDescriptionPreview(root, text) {",
  '  const panel = root.querySelector("[data-description-preview]");',
  "  if (!panel) return;",
  '  const value = typeof text === "string" ? text : descriptionPreviewText(root);',
  "  if (panel.dataset.previewText === value) return;",
  "  panel.dataset.previewText = value;",
  '  if (!value.trim()) { panel.innerHTML = ""; return; }',
  '  fetch("/api/markdown/preview", {',
  '    method: "POST",',
  '    headers: { "content-type": "application/json" },',
  "    body: JSON.stringify({ text: value })",
  "  }).then(function (response) {",
  '    if (!response.ok) throw new Error("markdown preview failed: " + response.status);',
  "    return response.json();",
  "  }).then(function (result) {",
  "    if (panel.dataset.previewText !== value) return;",
  '    panel.innerHTML = result && typeof result.html === "string" ? result.html : "";',
  "    enhanceDescriptionImages(panel);",
  "  }).catch(function () {",
  '    panel.textContent = "プレビューを表示できませんでした。";',
  "  });",
  "}",
  "function moveDescriptionTab(root, button, step) {",
  "  const buttons = descriptionTabButtons(root);",
  "  const index = buttons.indexOf(button);",
  "  if (index === -1) return;",
  "  const next = buttons[(index + step + buttons.length) % buttons.length];",
  "  if (!next) return;",
  "  next.focus();",
  '  selectDescriptionTab(root, next.getAttribute("data-description-tab") || "edit");',
  "}",
  "function focusDescriptionTab(root, edge) {",
  "  const buttons = descriptionTabButtons(root);",
  '  const button = edge === "start" ? buttons[0] : buttons[buttons.length - 1];',
  "  if (!button) return;",
  "  button.focus();",
  '  selectDescriptionTab(root, button.getAttribute("data-description-tab") || "edit");',
  "}",
  "function enhanceDescriptionImages(panel) {",
  '  Array.prototype.slice.call(panel.querySelectorAll("img")).forEach(function (image) {',
  '    image.setAttribute("loading", "lazy");',
  '    image.setAttribute("decoding", "async");',
  '    image.setAttribute("tabindex", "0");',
  '    image.setAttribute("role", "button");',
  '    image.setAttribute("aria-label", "画像を拡大");',
  '    if (image.dataset.imageEnhanced === "true") return;',
  '    image.dataset.imageEnhanced = "true";',
  '    if (image.parentNode && image.parentNode.classList && image.parentNode.classList.contains("description-figure")) return;',
  '    const figure = document.createElement("span");',
  '    figure.className = "description-figure";',
  '    const toggle = document.createElement("button");',
  '    toggle.type = "button";',
  '    toggle.className = "description-figure__toggle";',
  '    toggle.setAttribute("data-description-image-toggle", "");',
  '    toggle.textContent = "大きく表示";',
  '    toggle.addEventListener("click", function (event) {',
  "      event.preventDefault();",
  '      const expanded = figure.classList.toggle("is-expanded");',
  '      toggle.textContent = expanded ? "小さく戻す" : "大きく表示";',
  "    });",
  "    image.parentNode.insertBefore(figure, image);",
  "    figure.appendChild(image);",
  "    figure.appendChild(toggle);",
  "  });",
  "}",
  "function descriptionImage(node) {",
  '  return node && node.closest ? node.closest(".description-preview img, img.description-image") : null;',
  "}",
  "function descriptionLightbox() {",
  '  var box = document.querySelector("[data-description-lightbox]");',
  "  if (box) return box;",
  '  box = document.createElement("div");',
  '  box.className = "description-lightbox";',
  '  box.setAttribute("data-description-lightbox", "");',
  "  box.hidden = true;",
  "  box.innerHTML = '<button type=\"button\" class=\"description-lightbox__backdrop\" data-description-lightbox-close aria-label=\"閉じる\"></button>'",
  "    + '<figure class=\"description-lightbox__frame\"><img class=\"description-lightbox__image\" alt=\"\"><figcaption class=\"description-lightbox__bar\">'",
  "    + '<span data-description-lightbox-size></span><button type=\"button\" class=\"button small\" data-description-lightbox-close>閉じる</button></figcaption></figure>';",
  "  document.body.appendChild(box);",
  "  return box;",
  "}",
  "function openDescriptionImage(image) {",
  "  var box = descriptionLightbox();",
  '  var target = box.querySelector(".description-lightbox__image");',
  '  target.setAttribute("src", image.getAttribute("src") || "");',
  '  target.setAttribute("alt", image.getAttribute("alt") || "");',
  '  var size = box.querySelector("[data-description-lightbox-size]");',
  '  if (size) size.textContent = (image.naturalWidth || 0) + " × " + (image.naturalHeight || 0);',
  "  box.__returnTo = image;",
  "  box.hidden = false;",
  '  var close = box.querySelector("[data-description-lightbox-close]");',
  "  if (close) close.focus();",
  "}",
  "function closeDescriptionImage() {",
  '  var box = document.querySelector("[data-description-lightbox]");',
  "  if (!box || box.hidden) return;",
  "  box.hidden = true;",
  "  var back = box.__returnTo;",
  "  if (back && document.contains(back)) back.focus();",
  "}",
  "function handleDescriptionImageClick(event) {",
  '  if (event.target.closest && event.target.closest("[data-description-lightbox-close]")) { closeDescriptionImage(); return; }',
  "  const image = descriptionImage(event.target);",
  "  if (!image) return;",
  "  event.preventDefault();",
  "  openDescriptionImage(image);",
  "}",
  "function handleDescriptionImageKeydown(event) {",
  '  if (event.key === "Escape") { closeDescriptionImage(); return; }',
  '  if (event.key !== "Enter" && event.key !== " ") return;',
  "  const image = descriptionImage(event.target);",
  "  if (!image) return;",
  "  event.preventDefault();",
  "  openDescriptionImage(image);",
  "}",
  "function handleDescriptionTabClick(event) {",
  "  const button = descriptionTabButton(event.target);",
  "  const root = button ? descriptionTabRoot(button) : null;",
  "  if (!button || !root) return;",
  '  selectDescriptionTab(root, button.getAttribute("data-description-tab") || "edit");',
  "}",
  "function handleDescriptionTabKeydown(event) {",
  "  const button = descriptionTabButton(event.target);",
  "  const root = button ? descriptionTabRoot(button) : null;",
  "  if (!button || !root) return;",
  '  if (event.key === "ArrowRight") { event.preventDefault(); moveDescriptionTab(root, button, 1); return; }',
  '  if (event.key === "ArrowLeft") { event.preventDefault(); moveDescriptionTab(root, button, -1); return; }',
  '  if (event.key === "Home") { event.preventDefault(); focusDescriptionTab(root, "start"); return; }',
  '  if (event.key === "End") { event.preventDefault(); focusDescriptionTab(root, "end"); }',
  "}",
  "function refreshDescriptionTabs() {",
  '  document.querySelectorAll("[data-description-tabs]").forEach(function (root) {',
  "    const selected = root.querySelector('[data-description-tab][aria-selected=\"true\"]');",
  '    if (selected && selected.getAttribute("data-description-tab") === "preview") refreshDescriptionPreview(root);',
  "  });",
  "}",
  "// Delegated so the tabs react even when another script delays DOMContentLoaded.",
  'document.addEventListener("click", handleDescriptionTabClick);',
  'document.addEventListener("click", handleDescriptionImageClick);',
  'document.addEventListener("keydown", handleDescriptionTabKeydown);',
  'document.addEventListener("keydown", handleDescriptionImageKeydown);',
  "refreshDescriptionTabs();",
  'document.addEventListener("DOMContentLoaded", refreshDescriptionTabs);',
  'document.addEventListener("htmx:load", refreshDescriptionTabs);',
].join("\n");
